const hudCache = new Map();
/** kind: heart|food|bubble · state: full|half|empty → data URL 18×18. */
export function hudIcon(kind, state) {
  const k = kind + state; if (hudCache.has(k)) return hudCache.get(k);
  const cv = document.createElement("canvas"); cv.width = cv.height = 11;
  const g = cv.getContext("2d"), img = g.createImageData(11, 11);
  const rows = (kind === "heart" ? HEART : kind === "food" ? FOOD : BUBBLE).map(r => "." + r + ".");
  rows.unshift("..........."); rows.push("...........");
  let pal;
  if (kind === "heart") pal = state === "empty" ? { r: "#3a1a1a", l: "#3a1a1a", R: "#2a1010" } : { r: "#e01a2a", l: "#ff9a9a", R: "#8a0a14" };
  else if (kind === "food") pal = state === "empty" ? { m: "#3a2a1a", l: "#3a2a1a", M: "#2a1a10", w: "#4a4a40", W: "#3a3a30" } : { m: "#c0602a", l: "#f0a060", M: "#7a3a14", w: "#f4efe0", W: "#b8b0a0" };
  else pal = { b: "#3a8aff", w: "#ffffff" };
  let src = rows;
  if (state === "half") src = rows.map(r => r.slice(0, 6) + r.slice(6).replace(/[rlRmM]/g, "e"));
  paint(img.data, 11, src, { ...pal, e: kind === "heart" ? "#3a1a1a" : "#3a2a1a" }, kind === "bubble" ? null : "#000000");
  g.putImageData(img, 0, 0);
  const url = cv.toDataURL(); hudCache.set(k, url); return url;
}
