function paint(data, w, rows, pal, outline) {
  const put = (x, y, hexc) => { const o = (y * w + x) * 4; data[o] = parseInt(hexc.slice(1, 3), 16); data[o + 1] = parseInt(hexc.slice(3, 5), 16); data[o + 2] = parseInt(hexc.slice(5, 7), 16); data[o + 3] = 255; };
  const hgt = rows.length;
  rows.forEach((row, y) => { for (let x = 0; x < w; x++) { const c = row[x]; if (c && c !== "." && pal[c]) put(x, y, pal[c]); } });
  if (!outline) return;
  const solid = (x, y) => x >= 0 && y >= 0 && x < w && y < hgt && data[(y * w + x) * 4 + 3] === 255 && !(data[(y * w + x) * 4 + 3] === 254);
  const mark = [];
  for (let y = 0; y < hgt; y++) for (let x = 0; x < w; x++) if (data[(y * w + x) * 4 + 3] === 0 && (solid(x - 1, y) || solid(x + 1, y) || solid(x, y - 1) || solid(x, y + 1))) mark.push([x, y]);
  for (const [x, y] of mark) { put(x, y, outline); data[(y * w + x) * 4 + 3] = 255; }
}

/** Desenha o ícone 16×16 de um item (id ≥ 100) num ImageData. */
export function drawItemSprite(img, id, item) {
  if (item?.tool) {
    const kind = item.tool, mat = MATS[id % 5] || MATS[0];
    paint(img.data, 16, TOOLS[kind], { ...H, ...mat }, "#1a120a");
    return true;
  }
  const spec = ITEM_SPRITE[id]; if (!spec) return false;
  const [name, palOverride] = spec, [rows, pal] = S[name];
  paint(img.data, 16, rows, { ...(pal || {}), ...(palOverride || {}) }, "#1a120a");
  return true;
}

